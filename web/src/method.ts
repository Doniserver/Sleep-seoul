import type { Data } from "./data";
import { loadHeat } from "./heat";

/** 방법과 한계: 집을 알아보는 사람이 읽을 수 있게 짧게. 자세한 산식은 저장소의 docs/methodology.md */
export function renderMethod(root: HTMLElement, _data: Data) {
  root.innerHTML = `
  <article class="method">
    <h2>방법과 한계</h2>
    <p class="lead">이 지도의 색이 무엇을 뜻하고, 무엇을 뜻하지 않는지 적었습니다.</p>

    <h3>1. 무엇을 보여 주나요</h3>
    <ul>
      <li><b>집 밖 소음</b>입니다. 창문을 닫은 집 안 소음이나 층간소음이 아닙니다.</li>
      <li>자리마다 직접 잰 값이 아니라 <b>추정한 값</b>입니다. 서울 길가의 도시센서(S-DoT) <span id="m-n">약 870</span>곳이 <span id="m-y">한 해</span> 동안 잰 소음과, 그 주변의 도로·가게 사이의 관계를 찾아 서울 전체에 적용했습니다.</li>
      <li>색은 세 단계입니다. <b>조용</b>(칠하지 않음, 100점), <b>보통</b>(옅은 주황, 70점), <b>시끄러움</b>(빨강, 40점).</li>
    </ul>

    <h3>2. 어떻게 계산했나요</h3>
    <ol>
      <li>센서 자리마다 주변 조건을 셉니다. 가까운 도로(2·4·6차로 이상, 차로 수와 길이)와 음식점·술집·노래방·숙박업소의 수입니다.</li>
      <li>센서가 잰 값과 그 조건 사이의 관계를 찾습니다. "큰 도로가 가까울수록 시끄럽다"처럼, 조건이 클수록 소음이 같거나 커지는 관계만 씁니다.</li>
      <li>그 관계를 서울 전체에 10m 간격으로 적용한 뒤, 주변 약 150m를 부드럽게 묶어 30m 간격의 지도로 만듭니다.</li>
      <li>밤(22~06시) 평균, 낮(06~22시) 평균, 0~23시 시각별로 따로 계산합니다.</li>
    </ol>

    <h3>3. 조용·보통·시끄러움은 어떻게 나누나요</h3>
    <ul>
      <li>밤 평균 지도는 <b>52.5dB 미만이면 조용, 54.5dB 미만이면 보통, 그 이상이면 시끄러움</b>입니다. 이렇게 나누면 서울의 약 65%가 조용, 27%가 보통, 8%가 시끄러움이 됩니다.</li>
      <li>낮은 서울 전체가 밤보다 약 <span id="m-s">5</span>dB 시끄러워서, 낮 평균 지도는 기준을 그만큼 올렸습니다.</li>
      <li>시각별 지도는 기준이 서서히 바뀝니다. 한밤(23~04시)은 밤 기준, 한낮(08~19시)은 낮 기준이고, 아침과 저녁에는 그 사이 값을 씁니다. 그래서 <b>같은 크기의 소리라도 새벽에는 "시끄러움", 한낮에는 "조용"</b>이 될 수 있습니다. "그 시간대에 견줘 조용한가"를 보여 주는 방식입니다.</li>
      <li>세 단계는 <b>서울 안에서 견준 등급</b>입니다. 한 해 평균을 내고 주변을 묶으면 값이 좁은 범위에 모이기 때문에 경계의 dB 차이는 작지만, 실제로 큰길가와 주거지 안쪽의 소음 차이는 그보다 훨씬 큽니다. 시끄러움은 서울에서 가장 시끄러운 쪽 약 7%, 보통은 그다음 약 28%입니다.</li>
      <li>이 기준값은 잠정값입니다.</li>
    </ul>

    <h3>4. 동네별 보기</h3>
    <ul>
      <li>같은 소음 자료를 동네(행정동) 단위로 모은 것입니다. 그 동네 자리들의 평균 소음을 히트맵과 같은 기준으로 나눠 조용(100점)·보통(70점)·시끄러움(40점)을 매깁니다. 동네를 누르면 그 안에서 조용·보통·시끄러움 자리가 차지하는 비율도 나옵니다.</li>
      <li>도로가 300m 안에 없는 곳(산이나 강 한가운데)은 세지 않습니다.</li>
      <li>같은 동네 안에서도 큰길가와 안쪽은 다릅니다. 집을 볼 때는 히트맵으로 그 자리를 확인하세요.</li>
    </ul>

    <h3>5. 얼마나 믿을 수 있나요</h3>
    <ul>
      <li>센서를 하나씩 가리고 주변 조건만으로 그 자리의 값을 맞혀 보면, 평균 약 <span id="m-e">3.4</span>dB 어긋납니다. 세 단계로 나눈 것은 이 오차를 감안한 것입니다.</li>
      <li>센서는 간이측정기입니다(성능인증 1등급). 법정 소음 측정이 아닙니다.</li>
      <li>서울시가 법정 방식으로 잰 값과 견주면, 센서는 큰길가의 소음을 실제보다 낮게 재는 경향이 있습니다. 그래서 큰길가는 지도에 보이는 것보다 더 시끄러울 수 있습니다.</li>
      <li>공사장, 학교, 특정 가게, 철도, 비행기처럼 계산에 넣지 않은 소리는 지도에 나타나지 않습니다.</li>
      <li>집을 정하기 전에는 <b>밤에 직접 가서 들어 보는 것</b>이 가장 확실합니다. 이 지도는 어디를 먼저 볼지 고르는 데 쓰세요.</li>
    </ul>

    <h3>6. 자료 출처</h3>
    <ul>
      <li>소음: <a href="https://data.seoul.go.kr/dataList/OA-15969/S/1/datasetView.do" target="_blank" rel="noopener">서울특별시 스마트서울 도시데이터 센서(S-DoT) 환경정보</a> (서울 열린데이터광장, 공공누리 1유형)</li>
      <li>도로: <a href="https://www.data.go.kr/data/15146878/fileData.do" target="_blank" rel="noopener">국토지리정보원 연속수치지형도 도로중심선</a> (브이월드 공간정보 다운로드, 공공누리 1유형)</li>
      <li>가게 위치: 소상공인시장진흥공단 상가(상권)정보 (공공데이터포털)</li>
      <li>동네 경계: 통계청 행정동 경계 (<a href="https://github.com/vuski/admdongkor" target="_blank" rel="noopener">vuski/admdongkor</a>, CC BY 4.0)</li>
      <li>배경지도·항공사진·실사 3D·장소 찾기: <a href="https://www.vworld.kr" target="_blank" rel="noopener">브이월드</a> (국토교통부)</li>
    </ul>
  </article>`;
  loadHeat().then((h) => {
    const set = (id: string, v: string) => { const e = root.querySelector(id); if (e) e.textContent = v; };
    const maes = Object.values(h.frames).map((f) => f.mae);
    set("#m-n", String(h.n_sensors)); set("#m-y", `${h.year}년 한 해`);
    set("#m-s", String(Math.round(h.frames.day.cuts[0] - h.frames.night.cuts[0])));
    set("#m-e", (maes.reduce((a, b) => a + b, 0) / maes.length).toFixed(1));
  }).catch(() => {});
}
